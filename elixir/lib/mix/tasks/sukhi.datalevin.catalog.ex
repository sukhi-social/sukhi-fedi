defmodule Mix.Tasks.Sukhi.Datalevin.Catalog do
  @moduledoc """
  Regenerate `priv/datalevin/catalog.exs` from a migrated Postgres.

  The Datalevin store has no migrations. What it needs from the SQL schema —
  column types, defaults, unique indexes, foreign keys and their `ON DELETE`
  — is read once from a database the real migrations have been run on, and
  committed as data. The migrations stay the one place the schema is
  *written*; this file is only ever a snapshot of it.

      mix sukhi.migrate && mix sukhi.datalevin.catalog

  `test/sukhi_fedi/datalevin/catalog_test.exs` fails when the snapshot and
  the migrations disagree on the set of tables.
  """

  use Mix.Task

  @shortdoc "Snapshot the SQL schema for the Datalevin store"

  @columns """
  SELECT table_name, column_name, data_type, is_nullable = 'YES', column_default
  FROM information_schema.columns
  WHERE table_schema = 'public' AND table_name <> 'schema_migrations'
  ORDER BY table_name, ordinal_position
  """

  @indexes """
  SELECT t.relname, i.relname, ix.indisprimary,
         ARRAY(SELECT a.attname FROM unnest(ix.indkey) WITH ORDINALITY k(n, o)
               JOIN pg_attribute a ON a.attrelid = t.oid AND a.attnum = k.n ORDER BY k.o),
         pg_get_expr(ix.indpred, ix.indrelid),
         pg_get_indexdef(ix.indexrelid)
  FROM pg_index ix
  JOIN pg_class t ON t.oid = ix.indrelid
  JOIN pg_class i ON i.oid = ix.indexrelid
  JOIN pg_namespace n ON n.oid = t.relnamespace
  WHERE n.nspname = 'public' AND ix.indisunique
  ORDER BY t.relname, i.relname
  """

  @fks """
  SELECT t.relname, c.conname,
         ARRAY(SELECT a.attname FROM unnest(c.conkey) WITH ORDINALITY k(n, o)
               JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.n ORDER BY k.o),
         r.relname,
         ARRAY(SELECT a.attname FROM unnest(c.confkey) WITH ORDINALITY k(n, o)
               JOIN pg_attribute a ON a.attrelid = c.confrelid AND a.attnum = k.n ORDER BY k.o),
         c.confdeltype::text
  FROM pg_constraint c
  JOIN pg_class t ON t.oid = c.conrelid
  JOIN pg_class r ON r.oid = c.confrelid
  JOIN pg_namespace n ON n.oid = t.relnamespace
  WHERE c.contype = 'f' AND n.nspname = 'public'
  ORDER BY t.relname, c.conname
  """

  @impl Mix.Task
  def run(_args) do
    Mix.Task.run("app.config")
    {:ok, _} = Application.ensure_all_started(:ecto_sql)

    {:ok, catalog, _} =
      Ecto.Migrator.with_repo(SukhiFedi.Repo, fn repo ->
        %{rows: cols} = repo.query!(@columns)
        %{rows: idx} = repo.query!(@indexes)
        %{rows: fks} = repo.query!(@fks)
        build(cols, idx, fks)
      end)

    path = Path.join(:code.priv_dir(:sukhi_fedi) |> to_string(), "datalevin/catalog.exs")
    # Written next to the source, not into _build.
    path = if File.dir?("priv/datalevin"), do: "priv/datalevin/catalog.exs", else: path
    File.mkdir_p!(Path.dirname(path))

    body = """
    # SPDX-License-Identifier: AGPL-3.0-or-later
    # Generated by `mix sukhi.datalevin.catalog` — do not edit.
    #{inspect(catalog, pretty: true, limit: :infinity, printable_limit: :infinity, width: 100)}
    """

    File.write!(path, body)
    Mix.shell().info("wrote #{path}: #{map_size(catalog)} tables")
  end

  @doc false
  def build(cols, idx, fks) do
    tables =
      cols
      |> Enum.group_by(&hd/1)
      |> Map.new(fn {table, rows} ->
        columns =
          Enum.map(rows, fn [_, name, type, null, default] ->
            %{name: name, type: type, null: null, default: default}
          end)

        {table, %{columns: columns, pk: [], unique: [], fks: []}}
      end)

    tables =
      Enum.reduce(idx, tables, fn [table, name, primary, columns, pred, def], acc ->
        case acc do
          %{^table => t} when primary ->
            Map.put(acc, table, %{t | pk: columns})

          %{^table => t} ->
            u = %{name: name, keys: keys(def), where: where(pred)}
            Map.put(acc, table, %{t | unique: t.unique ++ [u]})

          _ ->
            acc
        end
      end)

    Enum.reduce(fks, tables, fn [table, name, columns, ref, ref_columns, del], acc ->
      fk = %{
        name: name,
        columns: columns,
        ref_table: ref,
        ref_columns: ref_columns,
        on_delete: on_delete(del)
      }

      case acc do
        %{^table => t} -> Map.put(acc, table, %{t | fks: t.fks ++ [fk]})
        _ -> acc
      end
    end)
  end

  # The key list of `CREATE UNIQUE INDEX … USING btree (k1, k2) WHERE …`:
  # plain columns, or `lower(col)`. Anything else is `{:unsupported, text}`,
  # which the adapter refuses to enforce silently (see Catalog).
  defp keys(def) do
    [_, rest] = String.split(def, "USING btree (", parts: 2)
    rest
    |> key_text()
    |> split_top()
    |> Enum.map(fn k ->
      k = String.trim(k)

      cond do
        Regex.match?(~r/^\w+$/, k) -> {:col, k}
        m = Regex.run(~r/^lower\(\(?(\w+)\)?(::text)?\)$/, k) -> {:lower, Enum.at(m, 1)}
        true -> {:unsupported, k}
      end
    end)
  end

  # Text up to the parenthesis that closes the key list.
  defp key_text(rest) do
    {text, _} =
      rest
      |> String.graphemes()
      |> Enum.reduce_while({"", 0}, fn
        ")", {acc, 0} -> {:halt, {acc, 0}}
        ")", {acc, d} -> {:cont, {acc <> ")", d - 1}}
        "(", {acc, d} -> {:cont, {acc <> "(", d + 1}}
        c, {acc, d} -> {:cont, {acc <> c, d}}
      end)

    text
  end

  defp split_top(text) do
    {parts, cur, _} =
      text
      |> String.graphemes()
      |> Enum.reduce({[], "", 0}, fn
        ",", {ps, cur, 0} -> {[cur | ps], "", 0}
        "(", {ps, cur, d} -> {ps, cur <> "(", d + 1}
        ")", {ps, cur, d} -> {ps, cur <> ")", d - 1}
        c, {ps, cur, d} -> {ps, cur <> c, d}
      end)

    Enum.reverse([cur | parts])
  end

  # `WHERE (a IS NULL) AND (b IS NOT NULL)` → [{:null, "a"}, {:not_null, "b"}]
  defp where(nil), do: []

  defp where(pred) do
    parts = Regex.scan(~r/(\w+) IS (NOT )?NULL/, pred)
    stripped = Regex.replace(~r/[()\s]|AND|(\w+) IS (NOT )?NULL/, pred, "")

    if stripped == "" and parts != [] do
      Enum.map(parts, fn
        [_, col] -> {:null, col}
        [_, col, ""] -> {:null, col}
        [_, col, _] -> {:not_null, col}
      end)
    else
      [{:unsupported, pred}]
    end
  end

  defp on_delete("c"), do: :cascade
  defp on_delete("n"), do: :nilify
  defp on_delete("r"), do: :restrict
  defp on_delete("d"), do: :default
  defp on_delete(_), do: :none
end
